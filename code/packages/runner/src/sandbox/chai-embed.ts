/**
 * Turns chai's single-file ESM bundle into one script for the sandbox: the bundle's body inside a
 * function that returns `expect`,
 * `assert` and `AssertionError`, so evaluating it in a context defines no
 * globals. `scripts/embed-chai.ts` writes the result to
 * `chai-source.generated.ts`; a test checks that file is current.
 */

const NEEDED = ['expect', 'assert', 'AssertionError'] as const;

/**
 * chai's plugin events use `EventTarget` and `Event`, which QuickJS lacks.
 * The sandbox never loads chai plugins, so inert stand-ins are enough; they
 * stay inside the wrapper function.
 */
const EVENT_SHIM =
  'class Event { constructor(type) { this.type = type; } }\n' +
  'class EventTarget { addEventListener() {} removeEventListener() {} dispatchEvent() { return true; } }\n';

/** The script: evaluates to `{ expect, assert, AssertionError }`. */
export function renderChaiSource(bundle: string): string {
  const match = /\nexport\s*\{([^}]*)\};?\s*$/.exec(bundle);
  if (match?.[1] === undefined) throw new Error('chai bundle: no trailing export list');
  const body = bundle.slice(0, match.index);
  if (/^\s*import\b/m.test(body)) throw new Error('chai bundle: expected no imports');
  const locals = new Map<string, string>();
  for (const entry of match[1].split(',')) {
    const [local = '', exported = local] = entry.trim().split(/\s+as\s+/);
    if (local !== '') locals.set(exported, local);
  }
  const returned = NEEDED.map((name) => {
    const local = locals.get(name);
    if (local === undefined) throw new Error(`chai bundle: ${name} is not exported`);
    return `${name}: ${local}`;
  });
  return `(function () {\n'use strict';\n${EVENT_SHIM}${body}\nreturn { ${returned.join(', ')} };\n})()`;
}

/** The generated TypeScript module's text. */
export function renderChaiModule(bundle: string, version: string): string {
  return (
    `// Generated by packages/runner/scripts/embed-chai.ts from chai ${version}. Do not edit.\n` +
    `// Regenerate from the repository root: node --import tsx packages/runner/scripts/embed-chai.ts\n\n` +
    `/** The chai version embedded below. */\n` +
    `export const CHAI_VERSION = ${JSON.stringify(version)};\n\n` +
    `/** chai's \`expect\`, \`assert\` and \`AssertionError\` as one script. */\n` +
    `export const CHAI_SOURCE = ${JSON.stringify(renderChaiSource(bundle))};\n`
  );
}
